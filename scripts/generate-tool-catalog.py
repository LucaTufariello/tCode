#!/usr/bin/env python3
"""Refresh the curated CPython 3.12 / arm64 wheel lock from PyPI release metadata.
This is a maintainer command, never executed by an imported language pack.
"""
import json
import pathlib
import urllib.request
ROOT = pathlib.Path(__file__).resolve().parents[1]
rows = []
for line in (ROOT / 'docs/tool-requirements.txt').read_text().splitlines():
    if not line:
        continue
    name, version = line.split('==')
    with urllib.request.urlopen(f'https://pypi.org/pypi/{name}/{version}/json', timeout=30) as response:
        metadata = json.load(response)
    candidates = []
    for wheel in metadata['urls']:
        filename = wheel['filename']
        if not filename.endswith('.whl'):
            continue
        tags = filename[:-4].rsplit('-', 3)
        python_tag, abi, platform = tags[-3:]
        universal = platform == 'any' and ('py3' in python_tag.split('.') or python_tag == 'py2.py3')
        native = ('arm64' in platform or 'universal2' in platform) and (python_tag in ('cp312', 'py3', 'py2.py3') or (abi == 'abi3' and python_tag in ('cp37','cp38','cp39','cp310','cp311','cp312')))
        if universal or native:
            candidates.append(wheel)
    if not candidates:
        raise SystemExit(f'No compatible CPython 3.12 macOS arm64 wheel: {line}')
    candidates.sort(key=lambda row: ('arm64' not in row['filename'], 'cp312' not in row['filename'], row['filename']))
    chosen = candidates[0]
    rows.append(dict(name=name, version=version, filename=chosen['filename'], url=chosen['url'], sha256=chosen['digests']['sha256'], size=chosen['size']))
    print(name, version, chosen['filename'])
output = ROOT / 'catalog/python-wheels.json'
output.write_text(json.dumps(dict(python='3.12', platform='macOS arm64', wheels=rows), indent=2) + '\n')
print(output)

# Embed the allowlist in native code: imported JSON cannot provide installers.
lines = ['// Generated by scripts/generate-tool-catalog.py; official PyPI SHA-256 wheel lock.', 'import Foundation', 'enum PythonWheelLock {', '  static let downloads: [ToolDownload] = [']
for row in rows:
    lines.append('    ToolDownload(url: URL(string: ' + json.dumps(row['url']) + ')!, sha256: ' + json.dumps(row['sha256']) + ', filename: ' + json.dumps(row['filename']) + ', size: ' + str(row['size']) + '),')
lines += ['  ]', '}']
(ROOT / 'Sources/TCodeCore/PythonWheelLock.swift').write_text('\n'.join(lines) + '\n')
